package com.sf.station.parcel.domain;

/**
 * 滞留档位（F4）。
 *
 * <p><b>派生属性，不落库、不设定时任务</b>：由 {@code now − inbound_at} 在查询时实时计算。
 * 落库只会引入"任务未跑到显示错误""取件后忘记回滚"两类不一致。
 *
 * <p>这与 F6 回炉形成对照，判据是同一条：<b>是否影响他人对资源的获取</b>。
 * 滞留不改变任何资源归属，故不落库；回炉改变码槽位归属，故必须落库。
 */
public enum OverdueLevel {
    /** 48 小时内，正常 */
    NORMAL,
    /** 48 ~ 72 小时，橙色预警 */
    WARN,
    /** 超过 72 小时，红色告警 */
    ALERT
}
